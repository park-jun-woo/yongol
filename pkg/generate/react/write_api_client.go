//ff:what writeAPIClient — src/lib/api.ts 에 operationId 기반 api 객체 방출

package react

import (
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/getkin/kin-openapi/openapi3"
)

// writeAPIClient emits src/lib/api.ts shaped as
//
//	export const api = {
//	  <OperationID>: (args: Req<'OperationID'>) => client.METHOD(path, { ... } as any).then(r => r.data as Res<'OperationID'>),
//	  ...
//	}
//
// The object key matches the OpenAPI operationId exactly (PascalCase or
// camelCase — preserved). This is the contract XOT-1 checks against at
// validate time.
//
// When hasAuthz is true, a JWT middleware is registered on the client that
// attaches the Bearer token from localStorage to every outgoing request.
func writeAPIClient(srcDir string, doc *openapi3.T, hasAuthz bool) error {
	if err := os.MkdirAll(filepath.Join(srcDir, "lib"), 0o755); err != nil {
		return err
	}

	var b strings.Builder
	b.WriteString("// Generated by yongol. Do not edit.\n")
	b.WriteString("// Source of truth: specs/api/openapi.yaml (operationId-keyed).\n")
	b.WriteString("import createClient from 'openapi-fetch'\n")
	b.WriteString("import type { paths, operations } from '../types/api'\n\n")
	writeReqResTypes(&b)
	b.WriteString("const client = createClient<paths>({ baseUrl: '/api' })\n")

	if hasAuthz {
		writeAuthzMiddleware(&b)
	}

	b.WriteString("\n")

	if doc == nil || doc.Paths == nil {
		b.WriteString("export const api = {}\n")
		return os.WriteFile(filepath.Join(srcDir, "lib", "api.ts"), []byte(b.String()), 0644)
	}

	entries := collectEndpoints(doc)
	sort.Slice(entries, func(i, j int) bool { return entries[i].opID < entries[j].opID })

	b.WriteString("export const api = {\n")
	for _, ep := range entries {
		writeApiClientEntry(&b, ep)
	}
	b.WriteString("}\n")

	return os.WriteFile(filepath.Join(srcDir, "lib", "api.ts"), []byte(b.String()), 0644)
}
